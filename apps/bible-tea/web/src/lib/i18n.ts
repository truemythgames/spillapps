export const SUPPORTED_LOCALES = ["en", "es"] as const;
export type Locale = (typeof SUPPORTED_LOCALES)[number];

export function getLocale(astroLocale: string | undefined): Locale {
  if (astroLocale === "es") return "es";
  return "en";
}

/** Cloudflare Pages serves pages at trailing-slash URLs (bare URLs 308-redirect). */
export function withTrailingSlash(path: string): string {
  return path.endsWith("/") ? path : `${path}/`;
}

/** English path → Spanish path when the slug differs. */
